# frozen_string_literal: true

require "test_helper"
require "open3"
require "rbconfig"
require "fileutils"
require "protostar/cli"

# `protostar FILE.proto`: compile by default, the file's directory as the
# include path, stdout for a single file
class CliDefaultsTest < Minitest::Test
  ROOT = File.expand_path("../..", __dir__)
  EXE = File.join(ROOT, "exe/protostar")
  PROJECT = File.join(ROOT, "test/fixtures/project")

  def protostar(*args, chdir: PROJECT)
    out, err, status = Open3.capture3(RbConfig.ruby, EXE, *args, chdir: chdir)
    [out, err, status.exitstatus]
  end

  def ruby_for(name, root)
    file = Protostar::Compiler.new(include_paths: [root]).compile([name], source_info: true).find { |f| f.name == name }
    Protostar::Compiler::Emitters::Ruby.new.file(file)
  end

  def write(dir, files)
    files.each do |path, source|
      FileUtils.mkdir_p(File.join(dir, File.dirname(path)))
      File.write(File.join(dir, path), source)
    end
  end

  def test_one_file_prints_its_ruby_with_its_directory_as_the_include_path
    out, err, status = protostar("proto/acme/person.proto")
    assert_equal [ruby_for("person.proto", File.join(PROJECT, "proto/acme")), "", 0], [out, err, status]
    assert_includes out, "Generated by protostar from person.proto."
  end

  def test_compile_subcommand_does_the_same
    assert_equal protostar("proto/acme/person.proto"), protostar("compile", "proto/acme/person.proto")
  end

  def test_flags_without_the_subcommand
    tmpdir do |dir|
      assert_equal ["", "", 0], protostar("-Iproto", "--ruby_out=#{dir}", "acme/person.proto")
      assert_equal ruby_for("acme/person.proto", File.join(PROJECT, "proto")), File.read(File.join(dir, "acme/person_pb.rb"))
    end
  end

  def test_output_directory_gets_the_basename
    tmpdir do |dir|
      assert_equal ["", "", 0], protostar("--ruby_out=#{dir}", "--rbs_out=#{dir}", "proto/acme/person.proto")
      assert_equal %w[person_pb.rb person_pb.rbi person_pb.rbs], Dir.children(dir).sort
    end
  end

  def test_explicit_include_path_prints_to_stdout_with_warnings_on_stderr
    out, err, status = protostar("-Iproto", "acme/unused.proto")
    assert_equal ruby_for("acme/unused.proto", File.join(PROJECT, "proto")), out
    assert_equal ["proto/acme/unused.proto:5:1: warning: Import acme/person.proto is unused.\n", 0], [err, status]
  end

  def test_bundled_imports_still_come_last
    out, err, status = protostar("google/protobuf/timestamp.proto")
    assert_equal ["", 0], [err, status]
    assert_includes out, "Generated by protostar from google/protobuf/timestamp.proto."
  end

  def test_several_files_need_an_output_directory
    assert_equal ["", "2 files cannot share stdout; add --ruby_out=DIR to write a _pb.rb for each.\n", 1],
      protostar("proto/acme/person.proto", "proto/acme/editions.proto")
    assert_equal ["", "--include_imports writes a set of files; add --descriptor_set_out=FILE.\n", 1],
      protostar("--include_imports", "proto/acme/person.proto")
  end

  def test_inputs_in_two_directories_are_both_include_paths
    tmpdir do |dir|
      write(dir, {
        "a/order.proto" => %(syntax = "proto3";\nimport "money.proto";\nmessage Order { Money total = 1; }\n),
        "b/money.proto" => %(syntax = "proto3";\nmessage Money { int64 cents = 1; }\n)
      })
      Dir.mkdir(File.join(dir, "out"))
      assert_equal ["", "", 0], protostar("--ruby_out=out", "a/order.proto", "b/money.proto", chdir: dir)
      assert_equal %w[money_pb.rb money_pb.rbi money_pb.rbs order_pb.rb order_pb.rbi order_pb.rbs], Dir.children(File.join(dir, "out")).sort
      assert_includes File.read(File.join(dir, "out/order_pb.rb")), %(require "money_pb")
    end
  end

  def test_same_basename_in_two_directories
    tmpdir do |dir|
      write(dir, {"a/x.proto" => %(syntax = "proto3";\n), "b/x.proto" => %(syntax = "proto3";\n)})
      assert_equal ["", "a/x.proto and b/x.proto are both x.proto; pass -I with a directory above both to tell them apart.\n", 1],
        protostar("--ruby_out=.", "a/x.proto", "b/x.proto", chdir: dir)
    end
  end

  def test_input_shadowed_by_a_file_next_to_another_input
    tmpdir do |dir|
      write(dir, {"a/x.proto" => %(syntax = "proto3";\n), "a/y.proto" => %(syntax = "proto3";\n), "b/y.proto" => %(syntax = "proto3";\n)})
      assert_equal ["", "b/y.proto: Input is shadowed by a/y.proto, which is next to another input. Pass -I to choose one.\n", 1],
        protostar("--ruby_out=.", "a/x.proto", "b/y.proto", chdir: dir)
    end
  end

  def test_explicit_include_path_not_containing_the_file_is_protocs_error
    assert_equal ["", "proto/acme/person.proto: #{Protostar::CLI::NO_MAPPING}\n", 1],
      protostar("-Ibroken", "proto/acme/person.proto")
  end

  def test_import_from_a_parent_directory_gets_a_hint
    out, err, status = protostar("proto/acme/directory.proto")
    assert_equal ["", 1], [out, status]
    assert_equal <<~ERR, err
      acme/person.proto: File not found.
      proto/acme/directory.proto:5:1: Import "acme/person.proto" was not found or had errors.
      proto/acme/directory.proto:13:29: "Person" is not defined.
      proto/acme/directory.proto:14:44: "Person" is not defined.
      acme/person.proto is in proto/, which is not an include path. Add -I proto to find it there.
    ERR
    _, err, = protostar("-Iproto/acme", "proto/acme/directory.proto")
    refute_includes err, "Add -I", "an explicit -I keeps protoc's output"
  end

  def test_parse_errors_leave_stdout_empty
    assert_equal ["", "broken/bad.proto:5:13: Field number 1 has already been used in \"A\" by field \"x\". " \
      "Next available field number is 2.\n", 1], protostar("broken/bad.proto")
  end

  def test_stdin_is_refused
    assert_equal ["", "#{Protostar::CLI::NO_STDIN}\n", 1], protostar("-")
    assert_equal ["", "#{Protostar::CLI::NO_STDIN}\n", 1], protostar("compile", "-Iproto", "-")
  end

  def test_help_and_version_still_win
    out, _, status = protostar("--help")
    assert_includes out, "Usage: protostar [compile]"
    assert_includes out, "Without -I, the directory of each PROTO_FILE is an include path"
    assert_equal 0, status
    assert_equal ["protostar #{Protostar::VERSION}\n", "", 0], protostar("--version")
  end
end
