  def compile(sources)
    Protostar::Compiler.new.compile(sources.keys, sources: sources, source_info: true)
  end

  def cart_file
    compile("acme/shop.proto" => PROTO).find { |f| f.name == "acme/shop.proto" }
  end

  def test_native_rbi_of_a_file
    assert_equal({"acme/shop_pb.rbi" => NATIVE}, Emitters::ProtostarRbi.new.emit([cart_file]))
  end

  def test_native_rbi_names_what_the_classes_have
    files = compile("acme/shop.proto" => PROTO)
    registry = Protostar::Types::Registry.new
    files.each { |f| registry.define(f) }
    cart = registry.find("acme.shop.Cart")
    rbi = Emitters::ProtostarRbi.new.file(files.find { |f| f.name == "acme/shop.proto" })
    defs = rbi.scan(/^ {6}def ([A-Za-z_]+[?=]?)/).flatten - ["initialize"]
    assert_equal cart.public_instance_methods(false).reject { |m| m.start_with?("__") }.sort, defs.map(&:to_sym).sort
  end

  def test_google_rbi_of_a_file
