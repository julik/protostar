  end

  def test_files_without_types
    files = compile("empty.proto" => "syntax = \"proto3\";\n", "plain.proto" => "syntax = \"proto3\";\nmessage Plain {}\n")
    native = Emitters::ProtostarRbi.new.emit(files)
    assert_equal "# typed: strict\n\n# Generated by protostar from empty.proto. Do not edit.\n", native.fetch("empty_pb.rbi")
    assert_equal <<~RBI, native.fetch("plain_pb.rbi")
      # typed: strict

      # Generated by protostar from plain.proto. Do not edit.

      class Plain < ::Protostar::Message
        sig { params(fields: ::T.nilable(::T::Hash[::T.any(::Symbol, ::String), ::T.untyped])).void }
        def initialize(fields = nil); end
      end
    RBI
    assert_includes Emitters::Rbi.new.emit(files).fetch("plain_pb.rbi"), "  sig { void }\n  def initialize; end\n"
  end

  def test_bootstrap_namespaces
    file = Protostar::Compiler.new(include_paths: [], bundled_includes: true)
      .compile(["google/protobuf/duration.proto"]).find { |f| f.name == "google/protobuf/duration.proto" }
    assert_includes Emitters::ProtostarRbi.new.file(file), "module Protostar\n  module Google\n"
    assert_includes Emitters::Rbi.new.file(file), "module Google\n  module Protobuf\n    class Duration < ::Google::Protobuf::AbstractMessage"
  end

  def test_every_corpus_file_parses
    skip "Prism is Ruby 3.3 and later" unless prism?
    native = Emitters::ProtostarRbi.new
    google = Emitters::Rbi.new
    SignatureBatches.corpus_files(bootstrap: true).each_value do |f|
      [native, google].each do |emitter|
        rbi = emitter.file(f)
        result = Prism.parse(rbi)
        assert result.success?, "#{emitter.class} #{f.name}: #{result.errors.map(&:message).first(3)}"
      end
    end
  end

  # Every corpus file in both formats through `sorbet --no-config`, next to
  # the gem's own RBI, without a single error
  def test_sorbet_accepts_the_corpus
    skip "sorbet is not installed (BUNDLE_WITH=sorbet, or SORBET=path)" unless SorbetSupport.executable
    native = Emitters::ProtostarRbi.new
    google = Emitters::Rbi.new
    SignatureBatches.batches(SignatureBatches.corpus_files).each do |batch|
      tmpdir do |dir|
        SignatureBatches.write(dir, batch, native)
        out, ok = SorbetSupport.typecheck(SorbetSupport::RUNTIME_RBI, dir)
        assert ok, "#{batch.keys.first(3).join(", ")}...:\n#{out[0, 3000]}"
      end
    end
    SignatureBatches.batches(SignatureBatches.corpus_files(bootstrap: true)).each do |batch|
      tmpdir do |dir|
        SignatureBatches.write(dir, batch, google)
        out, ok = SorbetSupport.typecheck(SorbetSupport::GOOGLE_STUB, dir)
        assert ok, "#{batch.keys.first(3).join(", ")}...:\n#{out[0, 3000]}"
      end
    end
  end

  # An application using the classes in signatures: the types are real, so
  # the one typo in app.rb is the one thing Sorbet reports
  def test_sorbet_sees_through_the_classes
    skip "sorbet is not installed (BUNDLE_WITH=sorbet, or SORBET=path)" unless SorbetSupport.executable
    tmpdir do |dir|
      FileUtils.cp(File.join(FIXTURES, "app.rb"), dir)
      FileUtils.cp(File.join(FIXTURES, "shop.proto"), dir)
      assert_equal 0, Protostar::CLI.run(["compile", "-I", dir, "--ruby_out=#{dir}", "shop.proto"], out: StringIO.new, err: $stderr)
      assert_equal "# frozen_string_literal: true\n# typed: ignore\n", File.read(File.join(dir, "shop_pb.rb")).lines.first(2).join
      out, ok = SorbetSupport.typecheck(SorbetSupport::RUNTIME_RBI, dir)
      refute ok
      errors = out.lines.grep(/\A[^ ].*: .* https:\/\/srb\.help\/\d+$/)
      assert_equal 3, errors.size, out
      assert_match(/app\.rb:\d+: Revealed type: `Shop::Order` /, errors[0])
      assert_match(/app\.rb:\d+: Method `custmer_email` does not exist on `Shop::Order`/, errors[1])
      assert_match(/app\.rb:\d+: Assigning a value to `value` that does not match expected type `T.nilable\(String\)`/, errors[2])
    end
  end

