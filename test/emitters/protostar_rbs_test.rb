  def compile(sources)
    Protostar::Compiler.new.compile(sources.keys, sources: sources, source_info: true)
  end

  def test_signatures_of_a_file
    file = compile("acme/shop.proto" => PROTO).find { |f| f.name == "acme/shop.proto" }
    assert_equal({"acme/shop_pb.rbs" => EXPECTED}, Emitters::ProtostarRbs.new.emit([file]))
  end

  def test_the_signatures_name_what_the_classes_have
    files = compile("acme/shop.proto" => PROTO)
    registry = Protostar::Types::Registry.new
    files.each { |f| registry.define(f) }
    file = files.find { |f| f.name == "acme/shop.proto" }
    cart = registry.find("acme.shop.Cart")
    rbs = Emitters::ProtostarRbs.new.file(file)
    readers = rbs.scan(/^ {6}attr_reader ([a-z_]+)\(/).flatten
    writers = rbs.scan(/^ {6}attr_writer ([a-z_]+)\(/).flatten.map { |n| "#{n}=" }
    defs = rbs.scan(/^ {6}def ([a-z_?]+):/).flatten - ["initialize"]
    names = (readers + writers + defs).map(&:to_sym).sort
    assert_equal cart.public_instance_methods(false).reject { |m| m.start_with?("__") }.sort, names
    refute_includes rbs, "attr_reader hash", "a field named like a Message method has no reader"
    refute_includes rbs, "_const", "no google-protobuf readers"
    refute_includes rbs, "Google::Protobuf::RepeatedField"
  end

  def test_files_without_a_package_and_without_types
    files = compile("plain.proto" => "syntax = \"proto3\";\nmessage Plain {}\n", "empty.proto" => "syntax = \"proto3\";\n")
    out = Emitters::ProtostarRbs.new.emit(files)
    assert_equal "# Generated by protostar from empty.proto. Do not edit.\n", out.fetch("empty_pb.rbs")
    assert_equal <<~RBS, out.fetch("plain_pb.rbs")
      # Generated by protostar from plain.proto. Do not edit.

      class Plain < ::Protostar::Message
        type init_map = ::Hash[::Symbol | ::String, untyped]
        def initialize: (?init_map? fields, **untyped) -> void
      end
    RBS
  end

  def test_bootstrap_signatures_are_current
    out, err, status = Open3.capture3(RbConfig.ruby, File.join(ROOT, "script/bootstrap.rb"), "check")
    assert status.success?, out + err
  end

  # Every file of the corpus, and sig/ itself, through `rbs validate`. Files
  # declaring the same names go into separate runs.
  def test_rbs_accepts_the_signatures
    rbs = rbs_executable or skip "the rbs gem is not installed"
    files = {}
    CodecFixtures.goldens.each do |rel|
      SchemaFixtures.cached(rel)[0].files.each do |f|
        files[f.name] ||= f unless Emitters::BOOTSTRAP.include?(f.name)
      end
    end
    emitter = Emitters::ProtostarRbs.new
    batches(files).each do |batch|
      tmpdir do |dir|
        batch.each_value do |f|
          emitter.emit([f]).each do |path, content|
            FileUtils.mkdir_p(File.dirname(File.join(dir, path)))
            File.write(File.join(dir, path), content)
          end
        end
        out, err, status = Open3.capture3(RbConfig.ruby, rbs, "-I", SIG, "-I", dir, "validate")
        errors = (out + err).lines.grep(/ERROR|Error/)
        assert status.success? && errors.empty?, "#{batch.keys.first(3).join(", ")}...:\n#{(out + err)[0, 3000]}"
      end
    end
  end

  private

  def rbs_executable
    Gem.bin_path("rbs", "rbs")
  rescue Gem::Exception
    nil
  end

  # Groups of files, each with its imports, in which no two files declare the same name
  def batches(files)
    closure = lambda do |f, acc = {}|
      next acc if acc[f.name] || !files.key?(f.name)
      acc[f.name] = f
      f.dependencies.each { |d| closure.call(files[d], acc) if files[d] }
      acc
    end
    declared = lambda do |f|
      prefix = Emitters::Naming.module_path(f).join("::")
      (f.all_messages + f.all_enums).map { |d| "#{prefix}::#{Emitters::Naming.relative_constant(d)}" }
    end
    batches = []
    files.each_value do |f|
      group = closure.call(f)
      batch = batches.find do |b|
        group.all? { |name, g| b[:files][name] || declared.call(g).none? { |n| b[:names][n] } }
      end
      batch ||= (batches << {files: {}, names: {}}).last
      group.each do |name, g|
        next if batch[:files][name]
        batch[:files][name] = g
        declared.call(g).each { |n| batch[:names][n] = true }
      end
    end
    batches.map { |b| b[:files] }
  end
