# frozen_string_literal: true

module Protostar
  class Compiler
    module Emitters
      # Writes `_pb.rbs` signatures for the classes {Ruby} generates:
      # subclasses of `Protostar::Message`, repeated fields as Arrays, maps as
      # Hashes, writers typed as {Message::Coercion} accepts. Signatures for
      # `Protostar::Message` itself are in the gem's `sig/protostar.rbs`.
      # {Rbs} writes protoc's signatures for google-protobuf's classes instead.
      class ProtostarRbs
        include NativeNames

        # The mixins {WellKnown::MIXINS} includes, by full name, as RBS names
        MIXINS = {
          "google.protobuf.Any" => "::Protostar::WellKnown::Any",
          "google.protobuf.Timestamp" => "::Protostar::WellKnown::Timestamp",
          "google.protobuf.Duration" => "::Protostar::WellKnown::Duration",
          "google.protobuf.Struct" => "::Protostar::WellKnown::Struct",
          "google.protobuf.Value" => "::Protostar::WellKnown::Value",
          "google.protobuf.ListValue" => "::Protostar::WellKnown::ListValue"
        }.freeze

        # @param namespaces [Hash{String => String}] Ruby module paths by file name, as {Ruby} takes them
        def initialize(namespaces: {})
          @namespaces = namespaces
          @reserved = Message::Accessors.reserved
          @types = FieldTypes.new(FieldTypes::RBS) { |d| constant(d) }
        end

        # @param files [Array<Schema::File>]
        # @return [Hash{String => String}] output path to signatures
        def emit(files)
          files.to_h { |f| [Naming.require_name(f.name) + ".rbs", file(f)] }
        end

        # @param file [Schema::File]
        # @return [String]
        def file(file)
          Naming.check_ruby_package(file)
          @source = file.source_info
          p = Printer.new
          p.print("# Generated by protostar from #{file.name}. Do not edit.\n")
          modules = module_path(file)
          unless file.messages.empty? && file.enums.empty?
            p.print("\n")
            modules.each do |m|
              p.print("module #{m}\n")
              p.indent
            end
            first = [true]
            file.messages.each_with_index { |m, i| message(p, m, [4, i], first) }
            file.enums.each_with_index { |e, i| enum(p, e, [5, i], first) }
            modules.size.times do
              p.outdent
              p.print("end\n")
            end
          end
          p.to_s
        ensure
          @source = nil
        end

        private

        def enum(p, enum, path, first)
          blank(p, first)
          comment(p, path)
          p.print("module #{Naming.rubify_constant(enum.name)}\n")
          p.indent
          p.print("extend ::Protostar::Enum\n\n")
          seen = {}
          enum.values.each do |v|
            const = Protostar::Enum.constant_name(v.name)
            next if const.nil? || seen[const]
            seen[const] = true
            p.print("#{const}: #{v.number}\n")
          end
          p.print("\ntype names = #{enum.values.map { |v| ":#{symbol(v.name)}" }.uniq.join(" | ")}\n")
          p.outdent
          p.print("end\n")
        end

        # A Symbol literal for a name, quoted when RBS needs it
        def symbol(name)
          /\A[A-Za-z_][A-Za-z0-9_]*\z/.match?(name) ? name : name.inspect
        end

        def message(p, message, path, first)
          return if message.map_entry?
          blank(p, first)
          comment(p, path)
          p.print("class #{Naming.rubify_constant(message.name)} < ::Protostar::Message\n")
          p.indent
          inner = [true]
          message.nested_messages.each_with_index { |m, i| message(p, m, path + [3, i], inner) }
          message.nested_enums.each_with_index { |e, i| enum(p, e, path + [4, i], inner) }
          blank(p, inner)
          if (mixin = MIXINS[message.full_name])
            p.print("include #{mixin}\nextend #{mixin}::ClassMethods\n\n")
          end
          init_map(p, message)
          constructor(p, message)
          taken = @reserved.dup
          message.fields.each_with_index do |f, i|
            accessors(p, f, path + [2, i], taken)
          end
          message.real_oneofs.each do |o|
            which = :"which_#{o.name}"
            next if taken[which]
            taken[which] = true
            names = o.fields.map { |f| ":#{f.name}" }.uniq.join(" | ")
            p.print("def which_#{o.name}: () -> (#{names})?\n")
          end
          p.outdent
          p.print("end\n")
        end

        def init_map(p, message)
          if message.fields.empty?
            p.print("type init_map = ::Hash[::Symbol | ::String, untyped]\n")
            return
          end
          p.print("type init_map = {\n")
          p.indent
          message.fields.each_with_index do |f, i|
            comma = (i == message.fields.size - 1) ? "" : ","
            p.print("?#{f.name}: #{@types.write_type(f)}#{comma}\n")
          end
          p.outdent
          p.print("}\n")
        end

        # `new` takes a Hash, keywords, or both
        def constructor(p, message)
          if message.fields.empty?
            p.print("def initialize: (?init_map? fields, **untyped) -> void\n")
            return
          end
          p.print("def initialize: (\n")
          p.indent
          p.print("?init_map? fields")
          message.fields.each { |f| p.print(",\n?#{f.name}: #{@types.write_type(f)}") }
          p.outdent
          p.print("\n) -> void\n")
        end

        def accessors(p, field, path, taken)
          name = field.name
          read = @types.read_type(field)
          write = @types.write_type(field)
          reader = !taken[name.to_sym]
          writer = !taken[:"#{name}="]
          taken[name.to_sym] = taken[:"#{name}="] = true
          if reader || writer
            p.print("\n")
            comment(p, path)
            p.print("attr_reader #{name}(): #{read}\n") if reader
            p.print("attr_writer #{name}(): #{write}\n") if writer
          end
          return unless field.presence?
          has = :"has_#{name}?"
          clear = :"clear_#{name}"
          p.print("def #{has}: () -> bool\n") unless taken[has]
          p.print("def #{clear}: () -> void\n") unless taken[clear]
          taken[has] = taken[clear] = true
        end
      end
    end
  end
end
