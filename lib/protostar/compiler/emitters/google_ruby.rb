# frozen_string_literal: true

module Protostar
  class Compiler
    module Emitters
      # Writes the `_pb.rb` file protoc's own Ruby generator writes
      # (ruby_generator.cc): the serialized descriptor added to
      # google-protobuf's generated pool, and constants looked up from it.
      class GoogleRuby
        # @param pool [Schema::Pool, nil] where extensions used in options but defined in
        #   `import option` files are found
        def initialize(pool: nil)
          @pool = pool
        end

        # @param files [Array<Schema::File>]
        # @return [Hash{String => String}] output path to source
        def emit(files)
          files.to_h { |f| [Naming.require_name(f.name) + ".rb", file(f)] }
        end

        # @param file [Schema::File]
        # @return [String]
        # @raise [Emitters::Error] for a `ruby_package` protoc refuses
        def file(file)
          Naming.check_ruby_package(file)
          p = Printer.new
          p.print("# frozen_string_literal: true\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n" \
            "# source: #{file.name}\n\n")
          p.print("require 'google/protobuf'\n\n")
          unless file.dependencies.empty?
            file.dependencies.each { |dep| p.print("require '#{Naming.require_name(dep)}'\n") }
            p.print("\n")
          end
          p.print("\ndescriptor_data = \"#{GoogleRuby.ruby_escape(GoogleRuby.serialized(file, @pool))}\"\n\n" \
            "pool = ::Google::Protobuf::DescriptorPool.generated_pool\npool.add_serialized_file(descriptor_data)\n\n")
          modules = Naming.module_path(file)
          modules.each do |m|
            p.print("module #{m}\n")
            p.indent
          end
          file.messages.each { |m| message_assignment(p, "", m) }
          file.enums.each { |e| enum_assignment(p, "", e) }
          modules.size.times do
            p.outdent
            p.print("end\n")
          end
          p.to_s
        end

        # What protoc embeds: the file as `FileDescriptor::CopyTo` writes it,
        # without source info and with `json_name` only where the .proto set
        # one. Whether it was set is not kept, so a `json_name` equal to the
        # derived one is taken as not set.
        # @return [String] binary
        def self.serialized(file, pool = nil)
          hash = without_json_names(file.to_h)
          hash.delete(:source_code_info)
          Schema::Proto::HashCodec.encode(Schema::Proto.schema(:FileDescriptorProto), hash, file.extension_finder(pool))
        end

        def self.without_json_names(hash)
          out = hash.dup
          %i[message_type nested_type].each do |key|
            out[key] = out[key].map { |m| without_json_names(m) } if out[key]
          end
          %i[field extension].each do |key|
            next unless out[key]
            out[key] = out[key].map do |f|
              next f unless f[:json_name] == Schema.json_name(f[:name])
              f = f.dup
              f.delete(:json_name)
              f
            end
          end
          out
        end

        PRINTABLE = (0x20..0x7E)
        HEX = /[0-9A-Fa-f]/
        C_ESCAPES = {"\n" => "\\n", "\r" => "\\r", "\t" => "\\t", "\"" => "\\\"", "'" => "\\'", "\\" => "\\\\"}.freeze

        # absl::CHexEscape, then a backslash before every `#` that would
        # start an interpolation: ruby_generator.cc's RubyEscape
        def self.ruby_escape(bytes)
          escaped = +""
          last_hex = false
          bytes.each_byte do |b|
            c = b.chr
            hex = false
            if (e = C_ESCAPES[c])
              escaped << e
            elsif !PRINTABLE.cover?(b) || (last_hex && HEX.match?(c))
              escaped << format("\\x%02x", b)
              hex = true
            else
              escaped << c
            end
            last_hex = hex
          end
          escaped.gsub(/#(?=[{$@])/) { "\\#" }
        end

        private

        def message_assignment(p, prefix, message)
          return if message.map_entry?
          name = Naming.rubify_constant(message.name)
          p.print("#{prefix}#{name} = ::Google::Protobuf::DescriptorPool.generated_pool." \
            "lookup(\"#{message.full_name}\").msgclass\n")
          message.nested_messages.each { |m| message_assignment(p, "#{prefix}#{name}::", m) }
          message.nested_enums.each { |e| enum_assignment(p, "#{prefix}#{name}::", e) }
        end

        def enum_assignment(p, prefix, enum)
          p.print("#{prefix}#{Naming.rubify_constant(enum.name)} = ::Google::Protobuf::DescriptorPool.generated_pool." \
            "lookup(\"#{enum.full_name}\").enummodule\n")
        end
      end
    end
  end
end
