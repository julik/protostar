# frozen_string_literal: true

module Protostar
  class Compiler
    module Emitters
      # Writes `_pb.rbi` files for Sorbet describing the classes google-protobuf
      # (or protostar's shim of it) makes from protoc's `_pb.rb`, in the shape
      # tapioca's protobuf compiler gives them: subclasses of
      # `Google::Protobuf::AbstractMessage`, repeated fields as
      # `Google::Protobuf::RepeatedField[T]`, maps as `Google::Protobuf::Map[K, V]`.
      # Writers take what protoc's RBS says they take. The class methods are
      # declared on every class, so `Foo.decode` is a `Foo`.
      class Rbi
        KEYWORD = ProtostarRbi::KEYWORD
        KEYWORD_CONSTANTS = ProtostarRbi::KEYWORD_CONSTANTS
        # Methods every object has, which a field's accessor cannot replace;
        # fixed rather than read from Object, which loaded gems change
        RESERVED = %i[
          ! != !~ <=> == === __id__ __send__ class clone define_singleton_method display dup enum_for eql? equal?
          extend freeze frozen? hash inspect instance_eval instance_exec instance_of? instance_variable_defined?
          instance_variable_get instance_variable_set instance_variables is_a? itself kind_of? method methods nil?
          object_id private_methods protected_methods public_method public_methods public_send
          remove_instance_variable respond_to? send singleton_class singleton_method singleton_methods tap then
          to_enum to_s yield_self initialize to_h to_hash to_json to_proto [] []=
        ].to_h { |m| [m, true] }.freeze

        def initialize
          @types = FieldTypes.new(FieldTypes::Sorbet, google: true) { |d| constant(d) }
        end

        # Returns a Hash of output path to the RBI.
        #: (Array[Schema::File] files) -> Hash[String, String]
        def emit(files)
          files.to_h { |f| [Naming.require_name(f.name) + ".rbi", file(f)] }
        end

        #: (Schema::File file) -> String
        def file(file)
          Naming.check_ruby_package(file)
          @source = file.source_info
          @late = []
          p = Printer.new
          p.print("# typed: strict\n\n# Generated by protostar from #{file.name}, for google-protobuf's classes. " \
            "Do not edit.\n")
          modules = Naming.module_path(file)
          unless file.messages.empty? && file.enums.empty?
            p.print("\n")
            modules.each do |m|
              p.print("module #{m}\n")
              p.indent
            end
            first = [true]
            file.messages.each_with_index { |m, i| message(p, m, [4, i], first) }
            file.enums.each_with_index { |e, i| enum(p, e, [5, i], first) }
            modules.size.times do
              p.outdent
              p.print("end\n")
            end
          end
          p.print("\n") unless @late.empty?
          @late.each { |line| p.print(line) }
          p.to_s
        ensure
          @source = @late = nil
        end

        private

        def constant(descriptor)
          prefix = Naming.module_path(descriptor.file).map { |m| "::#{m}" }.join
          "#{prefix}::#{Naming.relative_constant(descriptor)}"
        end

        def blank(p, first)
          if first[0]
            first[0] = false
          else
            p.print("\n")
          end
        end

        def comment(p, path)
          text = @source&.location(path)&.leading_comments
          return if text.nil? || text.empty?
          text.split("\n").reject(&:empty?).each { |line| p.print("##{line}\n") }
        end

        def method(p, sig, definition)
          p.print("sig { #{sig} }\ndef #{definition}; end\n")
        end

        def enum(p, enum, path, first)
          blank(p, first)
          comment(p, path)
          p.print("module #{Naming.rubify_constant(enum.name)}\n")
          p.indent
          seen = {}
          enum.values.each_with_index do |v, i|
            const = Protostar::Enum.constant_name(v.name)
            next if const.nil? || seen[const]
            seen[const] = true
            if KEYWORD_CONSTANTS.include?(const)
              @late << "#{constant(enum)}::#{const} = ::T.let(#{v.number}, ::Integer)\n"
              next
            end
            comment(p, path + [2, i])
            p.print("#{const} = ::T.let(#{v.number}, ::Integer)\n")
          end
          p.print("\n") unless seen.empty?
          method(p, "params(number: ::Integer).returns(::T.nilable(::Symbol))", "self.lookup(number)")
          p.print("\n")
          method(p, "params(symbol: ::Symbol).returns(::T.nilable(::Integer))", "self.resolve(symbol)")
          p.print("\n")
          method(p, "returns(::Google::Protobuf::EnumDescriptor)", "self.descriptor")
          p.outdent
          p.print("end\n")
        end

        def message(p, message, path, first)
          return if message.map_entry?
          blank(p, first)
          comment(p, path)
          name = constant(message)
          p.print("class #{Naming.rubify_constant(message.name)} < ::Google::Protobuf::AbstractMessage\n")
          p.indent
          inner = [true]
          message.nested_messages.each_with_index { |m, i| message(p, m, path + [3, i], inner) }
          message.nested_enums.each_with_index { |e, i| enum(p, e, path + [4, i], inner) }
          blank(p, inner)
          class_methods(p, name)
          p.print("\n")
          constructor(p, message)
          taken = RESERVED.dup
          message.fields.each_with_index { |f, i| accessors(p, f, path + [2, i], taken) }
          message.oneofs.each_with_index do |o, i|
            lines = []
            lines << ["returns(::T.nilable(::Symbol))", o.name] if take(taken, o.name)
            lines << ["returns(::T::Boolean)", "has_#{o.name}?"] if take(taken, "has_#{o.name}?")
            lines << ["void", "clear_#{o.name}"] if take(taken, "clear_#{o.name}")
            next if lines.empty?
            p.print("\n")
            comment(p, path + [8, i])
            lines.each { |sig, definition| method(p, sig, definition) }
          end
          p.outdent
          p.print("end\n")
        end

        def class_methods(p, name)
          method(p, "params(data: ::String, options: ::T.untyped).returns(#{name})",
            "self.decode(data, options = ::T.unsafe(nil))")
          method(p, "params(message: #{name}, options: ::T.untyped).returns(::String)",
            "self.encode(message, options = ::T.unsafe(nil))")
          method(p, "params(json: ::String, options: ::T.untyped).returns(#{name})",
            "self.decode_json(json, options = ::T.unsafe(nil))")
          method(p, "params(message: #{name}, options: ::T.untyped).returns(::String)",
            "self.encode_json(message, options = ::T.unsafe(nil))")
          method(p, "returns(::Google::Protobuf::Descriptor)", "self.descriptor")
        end

        # protoc's classes take keywords (or one Hash, which Sorbet sees as keywords)
        def constructor(p, message)
          keywords = message.fields.select { |f| KEYWORD.match?(f.name) }
          params = keywords.map { |f| "#{f.name}: #{@types.init_type(f)}" }
          args = keywords.map { |f| "#{f.name}: nil" }
          if keywords.size < message.fields.size
            rest = "fields"
            rest += "_" while message.fields.any? { |f| f.name == rest }
            params << "#{rest}: ::T.untyped"
            args << "**#{rest}"
          end
          if params.empty?
            method(p, "void", "initialize")
            return
          end
          p.print("sig do\n")
          p.indent
          p.print("params(\n")
          p.indent
          p.print("#{params.join(",\n")}\n")
          p.outdent
          p.print(").void\n")
          p.outdent
          p.print("end\ndef initialize(\n")
          p.indent
          p.print("#{args.join(",\n")}\n")
          p.outdent
          p.print("); end\n")
        end

        def take(taken, name)
          name = name.to_sym
          return false if taken[name]
          taken[name] = true
        end

        def accessors(p, field, path, taken)
          name = field.name
          lines = []
          lines << ["returns(#{@types.read_type(field)})", name] if take(taken, name)
          lines << ["params(value: #{@types.write_type(field)}).void", "#{name}=(value)"] if take(taken, "#{name}=")
          wrapped = wrapped(field)
          if wrapped
            type = "::T.nilable(#{@types.read_one(wrapped)})"
            lines << ["returns(#{type})", "#{name}_as_value"] if take(taken, "#{name}_as_value")
            write = "::T.nilable(#{@types.write_one(wrapped)})"
            lines << ["params(value: #{write}).void", "#{name}_as_value=(value)"] if take(taken, "#{name}_as_value=")
          end
          if field.type == :enum && take(taken, "#{name}_const")
            lines << ["returns(#{field.repeated? ? "::T::Array[::Integer]" : "::Integer"})", "#{name}_const"]
          end
          lines << ["returns(::T::Boolean)", "has_#{name}?"] if field.presence? && take(taken, "has_#{name}?")
          lines << ["void", "clear_#{name}"] if take(taken, "clear_#{name}")
          return if lines.empty?
          p.print("\n")
          comment(p, path)
          lines.each { |sig, definition| method(p, sig, definition) }
        end

        # The value field of a wrapper type, which gets `_as_value` accessors
        def wrapped(field)
          return if field.repeated? || !field.message_type || !Rbs::WRAPPERS.include?(field.message_type.full_name)
          field.message_type.fields_by_number[1]
        end
      end
    end
  end
end
