# frozen_string_literal: true

module Protostar
  class Compiler
    module Emitters
      # Writes `_pb.rbi` files for Sorbet describing the classes {Ruby}
      # generates, with the same types {ProtostarRbs} gives them. The runtime
      # API (`Protostar::Message` and the rest) is in the gem's
      # `rbi/protostar.rbi`. {Rbi} describes google-protobuf's classes instead.
      class ProtostarRbi
        include NativeNames

        # A keyword parameter Ruby accepts; other field names go to `**`
        KEYWORD = /\A[a-z_][A-Za-z0-9_]*\z/
        # Constant names Ruby parses as keywords, set from outside the module
        KEYWORD_CONSTANTS = %w[BEGIN END].freeze

        # @param namespaces [Hash{String => String}] Ruby module paths by file name, as {Ruby} takes them
        def initialize(namespaces: {})
          @namespaces = namespaces
          @reserved = Message::Accessors.reserved
          @types = FieldTypes.new(FieldTypes::Sorbet) { |d| constant(d) }
        end

        # @param files [Array<Schema::File>]
        # @return [Hash{String => String}] output path to the RBI
        def emit(files)
          files.to_h { |f| [Naming.require_name(f.name) + ".rbi", file(f)] }
        end

        # @param file [Schema::File]
        # @return [String]
        def file(file)
          Naming.check_ruby_package(file)
          @source = file.source_info
          @late = []
          p = Printer.new
          p.print("# typed: strict\n\n# Generated by protostar from #{file.name}. Do not edit.\n")
          modules = module_path(file)
          unless file.messages.empty? && file.enums.empty?
            p.print("\n")
            modules.each do |m|
              p.print("module #{m}\n")
              p.indent
            end
            first = [true]
            file.messages.each_with_index { |m, i| message(p, m, [4, i], first) }
            file.enums.each_with_index { |e, i| enum(p, e, [5, i], first) }
            modules.size.times do
              p.outdent
              p.print("end\n")
            end
          end
          p.print("\n") unless @late.empty?
          @late.each { |line| p.print(line) }
          p.to_s
        ensure
          @source = @late = nil
        end

        private

        def enum(p, enum, path, first)
          blank(p, first)
          comment(p, path)
          p.print("module #{Naming.rubify_constant(enum.name)}\n")
          p.indent
          p.print("extend ::Protostar::Enum\n")
          seen = {}
          printed = 0
          enum.values.each_with_index do |v, i|
            const = Protostar::Enum.constant_name(v.name)
            next if const.nil? || seen[const]
            seen[const] = true
            if KEYWORD_CONSTANTS.include?(const)
              @late << "#{constant(enum)}::#{const} = ::T.let(#{v.number}, ::Integer)\n"
              next
            end
            commented = !@source&.location(path + [2, i])&.leading_comments.to_s.empty?
            p.print("\n") if printed.zero? || commented
            printed += 1
            comment(p, path + [2, i])
            p.print("#{const} = ::T.let(#{v.number}, ::Integer)\n")
          end
          p.outdent
          p.print("end\n")
        end

        def message(p, message, path, first)
          return if message.map_entry?
          blank(p, first)
          comment(p, path)
          p.print("class #{Naming.rubify_constant(message.name)} < ::Protostar::Message\n")
          p.indent
          inner = [true]
          message.nested_messages.each_with_index { |m, i| message(p, m, path + [3, i], inner) }
          message.nested_enums.each_with_index { |e, i| enum(p, e, path + [4, i], inner) }
          blank(p, inner)
          if (mixin = ProtostarRbs::MIXINS[message.full_name])
            p.print("include #{mixin}\nextend #{mixin}::ClassMethods\n")
            # the mixin is Enumerable, whose element type every includer restates
            p.print("extend ::T::Generic\n\nElem = type_member { {fixed: ::T.untyped} }\n") if message.full_name == "google.protobuf.ListValue"
            p.print("\n")
          end
          constructor(p, message)
          taken = @reserved.dup
          message.fields.each_with_index { |f, i| accessors(p, f, path + [2, i], taken) }
          message.real_oneofs.each do |o|
            which = :"which_#{o.name}"
            next if taken[which]
            taken[which] = true
            p.print("\nsig { returns(::T.nilable(::Symbol)) }\ndef #{which}; end\n")
          end
          p.outdent
          p.print("end\n")
        end

        # `new` takes a Hash, keywords, or both
        def constructor(p, message)
          names = message.fields.map(&:name)
          hash = free("fields", names)
          keywords = message.fields.select { |f| KEYWORD.match?(f.name) }
          rest = (keywords.size < message.fields.size) ? free("rest", names) : nil
          params = ["#{hash}: ::T.nilable(#{FieldTypes::Sorbet::FIELDS})"]
          args = ["#{hash} = nil"]
          keywords.each do |f|
            params << "#{f.name}: #{@types.write_type(f)}"
            args << "#{f.name}: nil"
          end
          if rest
            params << "#{rest}: ::T.untyped"
            args << "**#{rest}"
          end
          if params.size == 1
            p.print("sig { params(#{params.first}).void }\ndef initialize(#{args.first}); end\n")
            return
          end
          p.print("sig do\n")
          p.indent
          p.print("params(\n")
          p.indent
          p.print("#{params.join(",\n")}\n")
          p.outdent
          p.print(").void\n")
          p.outdent
          p.print("end\ndef initialize(\n")
          p.indent
          p.print("#{args.join(",\n")}\n")
          p.outdent
          p.print("); end\n")
        end

        # A parameter name no field has
        def free(name, names)
          name += "_" while names.include?(name)
          name
        end

        def accessors(p, field, path, taken)
          name = field.name
          reader = !taken[name.to_sym]
          writer = !taken[:"#{name}="]
          taken[name.to_sym] = taken[:"#{name}="] = true
          if reader || writer
            p.print("\n")
            comment(p, path)
            p.print("sig { returns(#{@types.read_type(field)}) }\ndef #{name}; end\n") if reader
            p.print("sig { params(value: #{@types.write_type(field)}).void }\ndef #{name}=(value); end\n") if writer
          end
          return unless field.presence?
          has = :"has_#{name}?"
          clear = :"clear_#{name}"
          p.print("sig { returns(::T::Boolean) }\ndef #{has}; end\n") unless taken[has]
          p.print("sig { void }\ndef #{clear}; end\n") unless taken[clear]
          taken[has] = taken[clear] = true
        end
      end
    end
  end
end
