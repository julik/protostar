# frozen_string_literal: true

module Protostar
  class Compiler
    module Emitters
      # Writes the `_services_pb.rb` stubs grpc-tools' Ruby plugin writes
      # (grpc's src/compiler/ruby_generator.cc). Comments come from source
      # info, so compile with it.
      class Grpc
        # @param files [Array<Schema::File>]
        # @return [Hash{String => String}] output path to source, for files with services only
        def emit(files)
          files.each_with_object({}) do |f, out|
            source = file(f)
            out[Grpc.output_name(f.name)] = source unless source.empty?
          end
        end

        # @param name [String] "foo/bar.proto"
        # @return [String] "foo/bar_services_pb.rb"
        # @raise [Emitters::Error] for a name protoc's plugin refuses
        def self.output_name(name)
          unless name.size > 6 && ".proto".include?(name[-1])
            raise Error, "Invalid proto file name:  must end with .proto"
          end
          name[0, name.size - 6] + "_services_pb.rb"
        end

        # @param file [Schema::File]
        # @return [String] empty when the file declares no services
        def file(file)
          return "" if file.services.empty?
          @source = file.source_info
          package = ruby_package(file)
          p = Printer.new
          p.print("# Generated by the protocol buffer compiler.  DO NOT EDIT!\n")
          p.print("# Source: #{file.name} for package '#{package}'\n")
          file_comments = file_comments(file)
          unless file_comments.empty?
            p.print("# Original file comments:\n")
            p.print(file_comments)
          end
          p.print("\nrequire 'grpc'\n")
          p.print("require '#{file.name.sub(".proto", "_pb")}'\n\n")
          modules = split(package)
          modules.each do |m|
            p.print("module #{Naming.package_to_module(m)}\n")
            p.indent
          end
          file.services.each_with_index { |s, i| service(p, s, [6, i]) }
          modules.size.times do
            p.outdent
            p.print("end\n")
          end
          p.to_s
        ensure
          @source = nil
        end

        private

        def service(p, service, path)
          return if service.rpcs.empty?
          p.print("module #{modularize(service.name)}\n")
          p.indent
          p.print(comments(path, true))
          p.print("class Service\n")
          p.indent
          p.print("\ninclude ::GRPC::GenericService\n\n")
          p.print("self.marshal_class_method = :encode\nself.unmarshal_class_method = :decode\n")
          p.print("self.service_name = '#{service.full_name}'\n\n")
          service.rpcs.each_with_index do |rpc, i|
            input = type_of(rpc.input_type)
            input = "stream(#{input})" if rpc.client_streaming?
            output = type_of(rpc.output_type)
            output = "stream(#{output})" if rpc.server_streaming?
            p.print(comments(path + [2, i], true))
            p.print("rpc :#{rpc.name}, #{input}, #{output}\n")
            p.print(comments(path + [2, i], false))
          end
          p.outdent
          p.print("end\n\nStub = Service.rpc_stub_class\n")
          p.outdent
          p.print("end\n")
          p.print(comments(path, false))
        end

        # The package in dotted form, `ruby_package`'s `::` turned into dots
        def ruby_package(file)
          file.options.ruby_package&.gsub("::", ".") || file.package
        end

        # std::getline splitting: no trailing empty piece
        def split(text)
          parts = text.split(".", -1)
          parts.pop if parts.last == ""
          parts
        end

        def modularize(name)
          return name if name.empty?
          out = name[0].upcase(:ascii)
          last_underscore = false
          name[1..].each_char do |c|
            if last_underscore && c != "_"
              out << c.upcase(:ascii)
            elsif c != "_"
              out << c
            end
            last_underscore = c == "_"
          end
          out
        end

        # grpc's RubyTypeOf: the message's Ruby constant path as grpc spells it
        def type_of(message)
          name = message.full_name
          file = message.file
          if file.options.ruby_package
            name = name.delete_prefix(file.package) if name.start_with?(file.package)
            name = name.delete_prefix(".")
            name = "#{ruby_package(file)}.#{name}"
          end
          parts = split(".#{name}")
          parts.each_with_index.map do |part, i|
            (i < parts.size - 1) ? modularize(part) : Naming.rubify_constant(part)
          end.join("::")
        end

        def lines(text)
          return [] if text.nil?
          parts = text.split("\n", -1)
          parts.pop if parts.last == ""
          parts
        end

        # GetPrefixedComments: detached and leading comments, or trailing ones
        def comments(path, leading)
          location = @source&.location(path)
          return "" unless location
          out = []
          if leading
            location.leading_detached_comments.each { |c| out.concat(lines(c)) << "" }
            out.concat(lines(location.leading_comments))
          else
            out.concat(lines(location.trailing_comments))
          end
          prefixed(out)
        end

        def prefixed(out)
          out.map do |line|
            if line.empty?
              "#\n"
            elsif line.start_with?(" ")
              "##{line}\n"
            else
              "# #{line}\n"
            end
          end.join
        end

        # The comments above the syntax line, printed raw: a `$` comes out doubled
        def file_comments(file)
          location = @source&.location([12])
          return "" unless location
          out = []
          location.leading_detached_comments.each { |c| out.concat(lines(c)) << "" }
          out.concat(lines(location.leading_comments))
          prefixed(out).gsub("$", "$$")
        end
      end
    end
  end
end
