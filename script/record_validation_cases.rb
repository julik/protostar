# frozen_string_literal: true

# Re-runs every snippet of test/compiler/validation_cases.rb through protoc
# and rewrites the file with what protoc printed for each.
#
#   ruby script/record_validation_cases.rb   # needs protoc 36.2 (rake protoc:install)
#
# To add a case, add an entry with its files and `protoc: []`, then run this.

require "tmpdir"
require "open3"
require "fileutils"

ROOT = File.expand_path("..", __dir__)
FIXTURE = File.join(ROOT, "test/compiler/validation_cases.rb")
PROTOC = ENV.fetch("PROTOC", File.expand_path("~/.cache/protostar/protoc-36.2/bin/protoc"))

load FIXTURE

def list(items, indent)
  return "[]" if items.empty?
  "[\n" + items.map { |item| "#{" " * (indent + 2)}#{item}" }.join(",\n") + "\n#{" " * indent}]"
end

entries = ValidationCases::CASES.map do |name, c|
  lines = Dir.mktmpdir do |dir|
    c[:files].each do |file, body|
      path = File.join(dir, file)
      FileUtils.mkdir_p(File.dirname(path))
      File.write(path, body)
    end
    _out, err, status = Open3.capture3(PROTOC, "-I#{dir}", "--descriptor_set_out=#{dir}/out.binpb",
      c[:files].keys.first, chdir: dir)
    [status.success?, err.gsub(dir + "/", "").lines.map(&:chomp).reject(&:empty?)]
  end
  files = c[:files].map { |file, body| "#{file.inspect} => #{body.inspect}" }
  "    #{name.inspect} => {\n" \
    "      files: {\n" + files.map { |f| "        #{f}" }.join(",\n") + "\n      },\n" \
    "      success: #{lines[0]},\n" \
    "      protoc: #{list(lines[1].map(&:inspect), 6)}\n" \
    "    }"
end

File.write(FIXTURE, <<~RUBY)
  # frozen_string_literal: true

  # Generated by script/record_validation_cases.rb, which runs each snippet
  # through protoc 36.2 as `protoc -I<dir> --descriptor_set_out=<tmp> <first file>`.
  # Each entry holds the files of the case and protoc's stderr lines.
  module ValidationCases
    CASES = {
  #{entries.join(",\n")}
    }.freeze
  end
RUBY
puts "recorded #{ValidationCases::CASES.size} cases"
