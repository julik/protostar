# frozen_string_literal: true

# Runs cheddar-me/pbbuilder's own test suite against protostar, unchanged.
#
#   ruby script/pbbuilder_suite.rb shim      # pbbuilder as published, google-protobuf replaced by shims/google-protobuf
#   ruby script/pbbuilder_suite.rb builder   # pbbuilder with llm/outputs/ws9-pbbuilder.patch, on Protostar::Builder
#   ruby script/pbbuilder_suite.rb shim --rails 7.2,8.0
#
# The clone lives in tmp/pbbuilder at PIN (PBBUILDER_REF overrides it). The
# builder variant clones that into tmp/pbbuilder-protostar and applies the
# patch on a branch; an existing tmp/pbbuilder-protostar is used as it is
# (it is where the patch is worked on), unless --fresh is given. Each Rails
# version gets a generated Gemfile under tmp/pbbuilder-suite/. Nothing from
# the clones is committed.

require "fileutils"
require "open3"
require "bundler"

REPO = File.expand_path("..", __dir__)
URL = "https://github.com/cheddar-me/pbbuilder"
PIN = ENV.fetch("PBBUILDER_REF", "3a071d5c6556c79eacd62d8f0501b122ac180bc7")
CLONE = File.join(REPO, "tmp", "pbbuilder")
FORK = File.join(REPO, "tmp", "pbbuilder-protostar")
PATCH = File.join(REPO, "llm", "outputs", "ws9-pbbuilder.patch")
GEMFILES = File.join(REPO, "tmp", "pbbuilder-suite")
SHIM = File.join(REPO, "shims", "google-protobuf")

# pbbuilder's Appraisals name 7.2 and 8.0; 8.1 is the current release
RAILS = {"7.2" => "~> 7.2.0", "8.0" => "~> 8.0.0", "8.1" => "~> 8.1.0"}.freeze

def run!(*cmd, chdir: REPO, env: {})
  puts "$ #{cmd.join(" ")}"
  system(env, *cmd, chdir: chdir, exception: true)
end

def git(dir, *args)
  run!("git", "-C", dir, *args)
end

def ensure_clone
  run!("git", "clone", "--quiet", URL, CLONE) unless File.directory?(File.join(CLONE, ".git"))
  git(CLONE, "fetch", "--quiet", "origin") unless system("git", "-C", CLONE, "cat-file", "-e", "#{PIN}^{commit}", err: File::NULL)
  git(CLONE, "checkout", "--quiet", "--detach", PIN)
  # the test helper regenerates test_proto_pb.rb with protoc when the .proto looks newer
  FileUtils.touch(File.join(CLONE, "test", "test_proto_pb.rb"))
  CLONE
end

def ensure_fork(fresh)
  ensure_clone
  FileUtils.rm_rf(FORK) if fresh
  unless File.directory?(File.join(FORK, ".git"))
    run!("git", "clone", "--quiet", CLONE, FORK)
    git(FORK, "checkout", "--quiet", "-b", "protostar", PIN)
    git(FORK, "apply", PATCH)
    git(FORK, "add", "-A")
    git(FORK, "-c", "user.name=protostar", "-c", "user.email=protostar@localhost", "commit", "--quiet", "-m", "pbbuilder on Protostar::Builder")
  end
  FORK
end

def gemfile(variant, rails, dir)
  path = File.join(GEMFILES, "#{variant}-rails-#{rails}", "Gemfile")
  FileUtils.mkdir_p(File.dirname(path))
  lines = [
    "# Generated by script/pbbuilder_suite.rb",
    "source \"https://rubygems.org\"",
    "gem \"pbbuilder\", path: #{dir.inspect}",
    "gem \"protostar\", path: #{REPO.inspect}"
  ]
  lines << "gem \"google-protobuf\", path: #{SHIM.inspect}" if variant == "shim"
  %w[activesupport activemodel actionview actionpack railties].each do |g|
    lines << "gem #{g.inspect}, #{RAILS.fetch(rails).inspect}"
  end
  lines += ["gem \"minitest\", \"~> 5.0\"", "gem \"pry\"", "gem \"rake\""]
  File.write(path, lines.join("\n") << "\n")
  path
end

# The test files are loaded by name so that nothing of pbbuilder's Rakefile
# (Appraisal) is involved
LOADER = <<~RUBY
  if ENV["PBBUILDER_VARIANT"] == "shim"
    require "google/protobuf"
    abort "google-protobuf is not the shim" unless Google::Protobuf::IMPLEMENTATION == :PROTOSTAR
  end
  Dir["test/**/*_test.rb"].sort.each { |f| require File.expand_path(f) }
RUBY

def suite(variant, rails, dir)
  env = {"BUNDLE_GEMFILE" => gemfile(variant, rails, dir), "PBBUILDER_VARIANT" => variant}
  Bundler.with_unbundled_env do
    system(env, "bundle check > /dev/null 2>&1 || bundle install --quiet", chdir: dir, exception: true)
    if variant == "builder"
      out, = Open3.capture2e(env, "bundle", "exec", "ruby", "-e", "puts Gem.loaded_specs.key?('google-protobuf')", chdir: dir)
      abort "the builder variant must not load google-protobuf" unless out.strip == "false"
    end
    puts "== pbbuilder (#{variant}) on Rails #{rails}"
    out, status = Open3.capture2e(env, "bundle", "exec", "ruby", "-Itest", "-Ilib", "-e", LOADER, chdir: dir)
    puts out
    [out[/\d+ runs, \d+ assertions, \d+ failures, \d+ errors, \d+ skips/], status.success?]
  end
end

variant = ARGV.shift
abort "usage: #{$0} shim|builder [--rails 7.2,8.0] [--fresh]" unless %w[shim builder].include?(variant)
versions = (i = ARGV.index("--rails")) ? ARGV.fetch(i + 1).split(",") : RAILS.keys
dir = (variant == "shim") ? ensure_clone : ensure_fork(ARGV.include?("--fresh"))

results = versions.map { |v| [v, *suite(variant, v, dir)] }
puts "\npbbuilder #{PIN[0, 7]} (#{variant}), Ruby #{RUBY_VERSION}:"
results.each { |v, summary, ok| puts "  Rails #{v}: #{summary || "no summary"}#{" FAILED" unless ok}" }
exit(results.all? { |_, _, ok| ok })
